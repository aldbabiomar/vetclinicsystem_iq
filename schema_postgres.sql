-- ============================================================ POINT OF SALE (Retail only)
CREATE TABLE IF NOT EXISTS sales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date TEXT NOT NULL,  -- actually a full timestamp (datetime.now().isoformat()), not date-only -- see note in data_integrity_framework.md
    cashier_id TEXT,
    subtotal DOUBLE PRECISION NOT NULL,
    discount_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
    discount_applied_by TEXT,
    total DOUBLE PRECISION NOT NULL,
    payment_method TEXT,
    -- Only populated for Cash sales — the cash physically handed over and
    -- the change handed back (already floored to the nearest 250 IQD
    -- note). NULL for any other payment method.
    cash_received DOUBLE PRECISION,
    change_given DOUBLE PRECISION,
    FOREIGN KEY (cashier_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS sale_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id INTEGER NOT NULL,
    item_id TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    unit_price DOUBLE PRECISION NOT NULL,
    line_total DOUBLE PRECISION NOT NULL,
    -- Cost snapshotted at sale time, alongside the row lock in
    -- pos_checkout — this is what lets COGS reporting reflect the actual
    -- cost basis of each sale instead of re-reading current inventory
    -- cost (which would retroactively change a past month's COGS every
    -- time an item's cost is edited). Nullable: an item without a
    -- cost_price set has nothing to snapshot.
    unit_cost DOUBLE PRECISION,
    FOREIGN KEY (sale_id) REFERENCES sales(id),
    FOREIGN KEY (item_id) REFERENCES inventory_list(id)
);
CREATE INDEX IF NOT EXISTS idx_saleitems_sale ON sale_items(sale_id);

-- ============================================================ REFUNDS (Admin only)
-- Two kinds: 'retail' (one or more products returned, identified by barcode,
-- with an option to put the stock back) and 'service' (a straight revenue
-- reduction against a Visit or Inpatient case, no stock impact). Both reduce
-- revenue in the P&L for the month the refund itself was processed in —
-- not the original sale/visit's month — matching normal accounting practice.
CREATE TABLE IF NOT EXISTS refunds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_type TEXT NOT NULL CHECK (refund_type IN ('retail','service')),
    refund_date DATE NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    restocked BOOLEAN NOT NULL DEFAULT FALSE,   -- retail only: were the returned items put back into inventory?
    visit_id TEXT,                          -- service only, optional link
    inpatient_case_id INTEGER,              -- service only, optional link
    reason TEXT,
    processed_by TEXT,
    created_at TEXT NOT NULL,
    FOREIGN KEY (visit_id) REFERENCES visits(id),
    FOREIGN KEY (inpatient_case_id) REFERENCES inpatient_cases(id)
);
CREATE INDEX IF NOT EXISTS idx_refunds_date ON refunds(refund_date);

CREATE TABLE IF NOT EXISTS refund_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id INTEGER NOT NULL,
    item_id TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    unit_price DOUBLE PRECISION NOT NULL,
    line_total DOUBLE PRECISION NOT NULL,
    FOREIGN KEY (refund_id) REFERENCES refunds(id),
    FOREIGN KEY (item_id) REFERENCES inventory_list(id)
);
CREATE INDEX IF NOT EXISTS idx_refunditems_refund ON refund_items(refund_id);

-- ============================================================ OPEX / P&L (monthly is the source; yearly rolls it up)
CREATE TABLE IF NOT EXISTS monthly_opex (
    month TEXT PRIMARY KEY,           -- 'YYYY-MM'
    rent DOUBLE PRECISION NOT NULL DEFAULT 0,
    salaries DOUBLE PRECISION NOT NULL DEFAULT 0,
    utilities DOUBLE PRECISION NOT NULL DEFAULT 0,
    marketing DOUBLE PRECISION NOT NULL DEFAULT 0,
    other DOUBLE PRECISION NOT NULL DEFAULT 0
);

-- Materialized per-month revenue/COGS, kept in sync incrementally by app.py
-- on every write that affects it (new sale, billing, refund, boarding total,
-- inpatient billing/discount, etc.) and fully rebuilt by
-- logic.recompute_full_summary() whenever a shared Price List / Inventory
-- Catalog cost or sale price changes, since those can retroactively affect
-- COGS/revenue for many past months at once. This is what lets Monthly &
-- Yearly P&L load instantly regardless of how many historical
-- billing/sales/refund rows exist, instead of re-scanning all of them on
-- every page view.
CREATE TABLE IF NOT EXISTS monthly_financial_summary (
    month TEXT PRIMARY KEY,           -- 'YYYY-MM'
    revenue DOUBLE PRECISION NOT NULL DEFAULT 0,
    cogs DOUBLE PRECISION NOT NULL DEFAULT 0,
    updated_at TEXT
);

-- ============================================================ APPOINTMENTS
-- Slot grid is generated dynamically from settings (appt_start_time / appt_end_time /
-- appt_slot_minutes) — no fixed slot table needed; slot labels (each slot's own start
-- time, e.g. '09:00', '09:30'...) are derived at render time from that range.
CREATE TABLE IF NOT EXISTS appointments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appt_date DATE NOT NULL,
    slot_label TEXT NOT NULL,          -- the slot's start time, e.g. '09:00', '09:30'...
    resource_type TEXT NOT NULL CHECK (resource_type IN ('vet','grooming')),
    resource_id TEXT,                  -- users.id when resource_type='vet'; NULL for grooming
    pet_name TEXT NOT NULL,
    owner_name TEXT NOT NULL,
    appointment_type TEXT NOT NULL CHECK (appointment_type IN ('Medical','Grooming')),
    reason TEXT,
    created_by TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_appt_date ON appointments(appt_date);

-- Enforces at the database level what logic.slot_conflict() only checks at
-- the application level: two appointments can't occupy the same slot for
-- the same vet/groomer. The app-level check-then-insert alone has a race
-- window — two concurrent bookings for the same slot can both pass the
-- check before either inserts. COALESCE(resource_id, '') is needed because
-- resource_id is NULL for grooming rows, and Postgres otherwise treats
-- every NULL as distinct under a plain UNIQUE constraint (which would let
-- unlimited grooming appointments stack into the same slot).
CREATE UNIQUE INDEX IF NOT EXISTS uq_appointments_slot
    ON appointments (appt_date, slot_label, resource_type, COALESCE(resource_id, ''));


-- ============================================================ BILLING SNAPSHOTS
-- Revenue/COGS reporting reads *current* Price List / Inventory Catalog
-- values only where nothing was sold/billed yet; once a line is
-- sold/billed, its price and cost are snapshotted here (or in
-- inpatient_billing.unit_price/unit_cost, sale_items.unit_cost above) so
-- a later price edit can never reach back and change a transaction that
-- already happened. Automatic visit billing is driven entirely by these
-- rows (price_id + quantity, added via the search-and-add billing UI) —
-- there's no comma-string intermediate anymore (billing.codes was
-- removed once this became the only way an Automatic bill gets built).
CREATE TABLE IF NOT EXISTS visit_billing_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id TEXT NOT NULL,
    price_id TEXT NOT NULL,
    name TEXT NOT NULL,
    category TEXT,
    quantity DOUBLE PRECISION NOT NULL DEFAULT 1,
    unit_price DOUBLE PRECISION NOT NULL,
    unit_cost DOUBLE PRECISION,
    created_at TEXT NOT NULL,
    FOREIGN KEY (visit_id) REFERENCES visits(id),
    FOREIGN KEY (price_id) REFERENCES price_list(id)
);
CREATE INDEX IF NOT EXISTS idx_visit_billing_lines_visit ON visit_billing_lines(visit_id);


-- ============================================================ CONSIGNMENT
-- A distributor's stock, sitting on your shelf: they're owed cost_price
-- per unit once it sells; you keep the markup. Consignment items are
-- ordinary Retail inventory_list rows (ownership_type='Consignment',
-- above) — they flow through the existing POS/audit/P&L pipeline
-- unmodified (see logic.py's consignment_* functions and
-- Consignment_Feature_Framework.md §2). These four tables are the
-- distributor-facing receiving/shrinkage/returns/settlement layer on top
-- of that shared data, not a second inventory system.

-- Stock the distributor drops off. Paired with an inventory_transactions
-- row (reason='consignment_receipt', +quantity) at insert time — see
-- logic.record_consignment_receipt() — so new stock is immediately
-- visible on Inventory Status and the next audit walk, same mechanism
-- POS checkout and refund restocking already use.
CREATE TABLE IF NOT EXISTS consignment_receipts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL,
    distributor_id TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    unit_cost_at_receipt DOUBLE PRECISION NOT NULL,
    received_date DATE NOT NULL,
    delivery_reference TEXT,
    notes TEXT,
    received_by TEXT,
    created_at TEXT NOT NULL,
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (received_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_consreceipts_item ON consignment_receipts(item_id);
CREATE INDEX IF NOT EXISTS idx_consreceipts_dist ON consignment_receipts(distributor_id);

-- Damaged/expired consignment stock, written off before it ever sold.
-- Paired with an inventory_transactions row (reason='shrinkage',
-- -quantity) at insert time, same shelf-count effect as a sale — see
-- logic.record_consignment_shrinkage(). liable_party decides whether
-- this adds to what's owed the distributor (§9/§7): 'Clinic' does,
-- 'Distributor' doesn't (they absorb the stock loss directly).
CREATE TABLE IF NOT EXISTS consignment_shrinkage (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL,
    distributor_id TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    reason TEXT NOT NULL CHECK (reason IN ('Damaged','Expired','Other')),
    liable_party TEXT NOT NULL CHECK (liable_party IN ('Distributor','Clinic')),
    liability_overridden BOOLEAN NOT NULL DEFAULT FALSE,
    unit_cost DOUBLE PRECISION NOT NULL,
    notes TEXT,
    logged_by TEXT,
    logged_at TEXT NOT NULL,
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (logged_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_consshrink_item ON consignment_shrinkage(item_id);
CREATE INDEX IF NOT EXISTS idx_consshrink_dist ON consignment_shrinkage(distributor_id);

-- Unsold stock physically handed back to the distributor — mirror image
-- of Receiving. Paired with an inventory_transactions row
-- (reason='consignment_return', -quantity) at insert time — see
-- logic.record_consignment_return(). No revenue/COGS/settlement impact:
-- nothing sold, so nothing owed either way; this never appears in
-- consignment_balance()'s formula (§7).
CREATE TABLE IF NOT EXISTS consignment_returns (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL,
    distributor_id TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    unit_cost_at_return DOUBLE PRECISION NOT NULL,
    return_date DATE NOT NULL,
    reason TEXT,
    notes TEXT,
    returned_by TEXT,
    created_at TEXT NOT NULL,
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (returned_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_consreturns_item ON consignment_returns(item_id);
CREATE INDEX IF NOT EXISTS idx_consreturns_dist ON consignment_returns(distributor_id);

-- A record of "paid the distributor for what's sold since we last
-- settled." amount_paid may be less than amount_owed (a confirmed
-- partial settlement) — the difference carries forward as the next
-- settlement's starting residual (see logic.consignment_balance, §7).
CREATE TABLE IF NOT EXISTS consignment_settlements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id TEXT NOT NULL,
    period_start TEXT NOT NULL,
    period_end TEXT NOT NULL,
    amount_owed DOUBLE PRECISION NOT NULL,
    amount_paid DOUBLE PRECISION NOT NULL,
    payment_method TEXT,
    notes TEXT,
    settled_by TEXT,
    created_at TEXT NOT NULL,
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (settled_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_conssettle_dist ON consignment_settlements(distributor_id);


