-- ============================================================ DISTRIBUTOR LEDGER
-- Manual bookkeeping only — lump-sum bills logged by hand and payments
-- against them, same shape as the owner-side billing/payments pattern
-- elsewhere in this file (a charge row, a separate payments-against-it
-- table, balance computed as charge minus Sum(payments), never stored).
-- Not linked to inventory, POS, or any report — every bill here is a
-- manual entry, not auto-created from anything.
CREATE TABLE IF NOT EXISTS distributor_bills (
    id TEXT PRIMARY KEY,                 -- allocated via next_id(db, "DB")
    distributor_id TEXT NOT NULL,
    bill_date DATE NOT NULL,
    bill_reference TEXT,                 -- the distributor's own paper/invoice number, optional
    total_amount DOUBLE PRECISION NOT NULL CHECK (total_amount >= 0),
    notes TEXT,
    created_at TEXT NOT NULL,
    created_by TEXT,
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (created_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_distbills_distributor ON distributor_bills(distributor_id);

CREATE TABLE IF NOT EXISTS distributor_bill_payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
    payment_date DATE NOT NULL,
    method TEXT,                         -- free text: 'Cash', 'Bank Transfer', etc.
    notes TEXT,
    created_at TEXT NOT NULL,
    created_by TEXT,
    FOREIGN KEY (bill_id) REFERENCES distributor_bills(id),
    FOREIGN KEY (created_by) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_distpayments_bill ON distributor_bill_payments(bill_id);

-- Inventory Catalog: Medical / Retail
-- (Declared before Price List: price_list.linked_item_id has an inline FK
-- into this table, and an inline FOREIGN KEY requires the referenced table
-- to already exist at CREATE TABLE time — unlike a later ALTER TABLE ADD
-- CONSTRAINT, table creation order here is load-bearing.)
CREATE TABLE IF NOT EXISTS inventory_list (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Medical' CHECK (category IN ('Medical','Retail')),
    unit TEXT,
    track_expiry BOOLEAN NOT NULL DEFAULT TRUE,
    cost_price DOUBLE PRECISION,
    distributor_id TEXT,
    -- 'Owned' (you bought this stock outright — the default) or
    -- 'Consignment' (a distributor's stock, sitting on your shelf; you
    -- owe them cost_price per unit only once it sells). Only meaningful
    -- for category='Retail' — enforced in app.py, not here, matching how
    -- barcode_source's mutual-exclusivity below is also app-enforced.
    -- For a Consignment item, cost_price keeps its existing meaning
    -- (per-unit cost) but the *payee* changes: it's what's owed to
    -- distributor_id, not what the clinic itself paid — same column,
    -- same downstream COGS math, different real-world counterparty.
    ownership_type TEXT NOT NULL DEFAULT 'Owned' CHECK (ownership_type IN ('Owned','Consignment')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    barcode TEXT UNIQUE,
    -- Which of the two mutually-exclusive ways this item's barcode was set
    -- up: a real code entered/scanned in from the manufacturer's own
    -- packaging, or one Vetzone IQ generated internally. NULL alongside a
    -- NULL barcode when neither has ever been set up. Never both at once —
    -- enforced in app.py, not just here.
    barcode_source TEXT CHECK (barcode_source IN ('manual','generated')),
    notes TEXT,
    FOREIGN KEY (distributor_id) REFERENCES distributors(id)
);

-- Price List: Service / Medicine / Retail
-- Medicine billing lines are priced by range and do NOT touch inventory stock.
-- Only Retail rows (optionally linked to an inventory item) are sold via POS and move stock.
CREATE TABLE IF NOT EXISTS price_list (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Service' CHECK (category IN ('Service','Medicine','Retail')),
    cost_price DOUBLE PRECISION,
    sale_price DOUBLE PRECISION,
    notes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    linked_item_id TEXT,             -- Retail rows only: links to inventory_list.id for POS
    can_discount BOOLEAN NOT NULL DEFAULT FALSE,   -- if false, a bill containing this item can't have a discount applied
    FOREIGN KEY (linked_item_id) REFERENCES inventory_list(id)
);

-- ============================================================ AUDITS (whole-catalog Save/Confirm sessions)
-- One session = one shelf-walk. "Not Started Yet" is simply the absence of a session
-- for a date; a session becomes 'Confirmed' (locked, can't be edited) the moment the
-- user presses Confirm, otherwise it stays 'Draft' ("Saved") and can be resumed/edited.
-- Only Confirmed sessions count toward Inventory Status / Ordering Sheet history.
CREATE TABLE IF NOT EXISTS audit_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_date DATE NOT NULL,
    performed_by TEXT,
    status TEXT NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft','Confirmed')),
    created_at TEXT NOT NULL,
    confirmed_at TEXT,
    FOREIGN KEY (performed_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS audit_session_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL,
    item_id TEXT NOT NULL,
    stock_counted DOUBLE PRECISION,
    received_since_prior DOUBLE PRECISION NOT NULL DEFAULT 0,
    reorder_threshold DOUBLE PRECISION,          -- NULL = inherit from the last confirmed audit
    critical_item INTEGER,           -- NULL = inherit
    target_coverage_days DOUBLE PRECISION,       -- NULL = inherit
    nearest_expiry_date DATE,
    notes TEXT,
    FOREIGN KEY (session_id) REFERENCES audit_sessions(id),
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    -- One line per item per session — app.py's _save_audit_lines() does
    -- INSERT ... ON CONFLICT (session_id, item_id) DO UPDATE against
    -- this, so two concurrent saves for the same session+item update the
    -- same row instead of racing to both insert.
    UNIQUE (session_id, item_id)
);
CREATE INDEX IF NOT EXISTS idx_auditlines_session ON audit_session_lines(session_id);
CREATE INDEX IF NOT EXISTS idx_auditlines_item ON audit_session_lines(item_id);

-- Real-time stock movement — ONLY from POS Retail sales (not Medicine billing).
CREATE TABLE IF NOT EXISTS inventory_transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL,
    change_qty DOUBLE PRECISION NOT NULL,
    reason TEXT NOT NULL,            -- 'sale' / 'manual_adjustment' / 'refund' /
                                      -- 'consignment_receipt' / 'shrinkage' / 'consignment_return'
    ref_id TEXT,
    timestamp TEXT NOT NULL,
    user_id TEXT,
    FOREIGN KEY (item_id) REFERENCES inventory_list(id)
);
CREATE INDEX IF NOT EXISTS idx_invtxn_item ON inventory_transactions(item_id);

-- ============================================================ VISITS (visit + wellness + grooming, one record)
CREATE TABLE IF NOT EXISTS visits (
    id TEXT PRIMARY KEY,
    patient_id TEXT NOT NULL,
    visit_type TEXT,                  -- 'Outpatient' / 'Inpatient'
    date DATE,
    doctor TEXT,                      -- free text, populated from a Vet-user dropdown on new entries
    weight_kg DOUBLE PRECISION,       -- patient's weight at this visit, in kilograms
    bcs INTEGER CHECK (bcs BETWEEN 1 AND 9),   -- Body Condition Score, 1-9 scale
    complaint TEXT,
    history TEXT,
    exam TEXT,
    treatment TEXT,
    case_status TEXT NOT NULL DEFAULT 'Needs Filling'
        CHECK (case_status IN ('Needs Filling','Ongoing','Admitted to Inpatient','Deceased/Euthanized',
                                'Lost to Follow Up','Resolved','Referred')),
    case_status_changed_at TEXT,      -- drives the 2-week "Lost to Follow Up" missed-flag clock
    updates_log TEXT,

    -- Follow-up (method, not type)
    followup_needed TEXT,             -- 'Y' / 'N'
    followup_method TEXT,             -- 'Physical Visit' / 'Phone Call'
    followup_reason TEXT,
    followup_date DATE,
    followup_status TEXT,             -- 'Pending' / 'Completed' / 'Cancelled' / 'N/A'

    -- Wellness reminder
    wellness_needed TEXT DEFAULT 'N',
    wellness_type TEXT,                -- 'Annual Vaccine' / 'Rabies Vaccine' / 'Deworming' / 'Spot On/Pill'
    wellness_next_dose_date DATE,
    wellness_contacted TEXT DEFAULT 'N',
    wellness_contact_method TEXT,      -- 'Phone Call' / 'Message'

    -- Grooming
    grooming_needed TEXT DEFAULT 'N',
    grooming_services TEXT,            -- comma-separated service names
    grooming_notes TEXT,
    grooming_admitted_items TEXT,
    grooming_status TEXT,              -- 'Waiting' / 'Ongoing' / 'Finished'
    grooming_contacted TEXT DEFAULT 'N',

    payment_status TEXT,               -- derived/display cache; real status computed from payments
    created_by TEXT,
    FOREIGN KEY (patient_id) REFERENCES patients(id)
);
CREATE INDEX IF NOT EXISTS idx_visits_patient ON visits(patient_id);
CREATE INDEX IF NOT EXISTS idx_visits_date ON visits(date);

-- Billing: Automatic (priced line items) OR Manual (single lump amount)
CREATE TABLE IF NOT EXISTS billing (
    visit_id TEXT PRIMARY KEY,
    billing_type TEXT NOT NULL DEFAULT 'Automatic' CHECK (billing_type IN ('Automatic','Manual')),
    -- codes column removed — Automatic billing is driven entirely by
    -- visit_billing_lines (price_id + quantity rows), not a comma string.
    manual_amount DOUBLE PRECISION,               -- Manual: single lump sum, exported as one "Veterinary Services" line
    date_billed DATE,
    discount_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
    discount_applied_by TEXT,
    notes TEXT,
    -- The final, 250-rounded payable figure for this bill (what
    -- compute_bill_totals() actually charges), kept in sync by
    -- logic.refresh_visit_billing_total() every time lines/discount/
    -- manual_amount change. Reports read this instead of re-deriving
    -- subtotal*(1-discount%), which would drift from the receipt by up
    -- to ~125 IQD once 250-rounding is applied.
    total DOUBLE PRECISION NOT NULL DEFAULT 0,
    FOREIGN KEY (visit_id) REFERENCES visits(id)
);

-- ============================================================ BOARDING
-- Relies on the existing Patient/Owner records — a boarding session just
-- links to a patient_id, the same way a Visit or Inpatient case does.
-- (Declared before Payments: payments.boarding_id has an inline FK into
-- this table, which requires the referenced table to already exist at
-- CREATE TABLE time.)
CREATE TABLE IF NOT EXISTS boarding_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id TEXT NOT NULL,
    entry_date DATE NOT NULL,
    dismissal_date DATE,              -- expected/actual end date; editable if the stay is extended or shortened
    admitted_items TEXT,
    special_needs BOOLEAN NOT NULL DEFAULT FALSE,   -- chronic disease or custom requirement flag
    special_needs_notes TEXT,
    room TEXT,
    price_per_day DOUBLE PRECISION,
    total DOUBLE PRECISION,           -- raw subtotal (price_per_day * nights, or entered manually) — pre-rounding
    -- The final, 250-rounded payable figure (what compute_bill_totals()
    -- actually charges on `total` above), kept in sync by
    -- logic.refresh_boarding_total() every time the session is saved.
    -- Reports read this instead of the raw `total`, which would drift
    -- from the receipt by up to ~125 IQD once 250-rounding is applied.
    billed_total DOUBLE PRECISION,
    dismissed BOOLEAN NOT NULL DEFAULT FALSE,   -- has the animal actually left yet
    created_by TEXT,
    FOREIGN KEY (patient_id) REFERENCES patients(id)
);
CREATE INDEX IF NOT EXISTS idx_boarding_patient ON boarding_sessions(patient_id);

-- "Something's Wrong!" incident log for a boarding stay
CREATE TABLE IF NOT EXISTS boarding_incidents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boarding_id INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    issue TEXT NOT NULL,
    contacted TEXT NOT NULL DEFAULT 'N',        -- 'Y' / 'N'
    contact_method TEXT,                        -- 'Phone Call' / 'Text Message'
    response TEXT,
    user_id TEXT,
    FOREIGN KEY (boarding_id) REFERENCES boarding_sessions(id)
);
CREATE INDEX IF NOT EXISTS idx_boardingincidents_boarding ON boarding_incidents(boarding_id);

-- ============================================================ INPATIENT SYSTEM
-- inpatient_cases is declared here (ahead of inpatient_updates/contact_log/
-- billing below, which logically belong to this same section) because
-- payments.inpatient_case_id has an inline FK into it, which requires the
-- referenced table to already exist at CREATE TABLE time.
CREATE TABLE IF NOT EXISTS inpatient_cases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id TEXT NOT NULL,
    visit_id TEXT,
    complaint TEXT,
    exam_findings TEXT,
    weight_kg DOUBLE PRECISION,       -- patient's weight at admission, in kilograms
    bcs INTEGER CHECK (bcs BETWEEN 1 AND 9),   -- Body Condition Score, 1-9 scale
    admission_date DATE NOT NULL,
    admitted_items TEXT,
    dismissed BOOLEAN NOT NULL DEFAULT FALSE,
    dismissal_date DATE,
    attending_vet_id TEXT,
    supervising_vet_id TEXT,
    discount_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
    discount_applied_by TEXT,
    created_by TEXT,
    -- The final, 250-rounded payable figure for this case (what
    -- compute_bill_totals() actually charges), kept in sync by
    -- logic.refresh_inpatient_total() every time procedures/discount
    -- change. Reports read this instead of re-deriving revenue from raw
    -- line math, which would drift from the receipt by up to ~125 IQD
    -- once 250-rounding is applied.
    total DOUBLE PRECISION NOT NULL DEFAULT 0,
    FOREIGN KEY (patient_id) REFERENCES patients(id),
    FOREIGN KEY (visit_id) REFERENCES visits(id),
    FOREIGN KEY (attending_vet_id) REFERENCES users(id),
    FOREIGN KEY (supervising_vet_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_inpatient_patient ON inpatient_cases(patient_id);

CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id TEXT,
    inpatient_case_id INTEGER,
    boarding_id INTEGER,
    amount DOUBLE PRECISION NOT NULL,
    method TEXT,
    date DATE NOT NULL,
    user_id TEXT,
    notes TEXT,
    -- All four nullable — a payment fills in exactly ONE of visit_id /
    -- inpatient_case_id / boarding_id (NULL always satisfies a foreign
    -- key regardless of match, so this only constrains whichever one is
    -- actually set). No ON DELETE CASCADE: nothing in this app
    -- hard-deletes a visit/inpatient case/boarding session/user, so the
    -- default ON DELETE RESTRICT is what we want — the database should
    -- refuse a delete that would orphan payment history, not silently
    -- allow or cascade-destroy it.
    FOREIGN KEY (visit_id) REFERENCES visits(id),
    FOREIGN KEY (inpatient_case_id) REFERENCES inpatient_cases(id),
    FOREIGN KEY (boarding_id) REFERENCES boarding_sessions(id),
    FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_payments_visit ON payments(visit_id);
CREATE INDEX IF NOT EXISTS idx_payments_case ON payments(inpatient_case_id);
CREATE INDEX IF NOT EXISTS idx_payments_boarding ON payments(boarding_id);

CREATE TABLE IF NOT EXISTS inpatient_updates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    note TEXT NOT NULL,
    user_id TEXT,
    FOREIGN KEY (case_id) REFERENCES inpatient_cases(id)
);
CREATE INDEX IF NOT EXISTS idx_inpupdates_case ON inpatient_updates(case_id);

CREATE TABLE IF NOT EXISTS inpatient_contact_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    picked_up INTEGER NOT NULL,
    staff_user_id TEXT,
    notes TEXT,
    FOREIGN KEY (case_id) REFERENCES inpatient_cases(id)
);
CREATE INDEX IF NOT EXISTS idx_inpcontact_case ON inpatient_contact_log(case_id);

CREATE TABLE IF NOT EXISTS inpatient_billing (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id INTEGER NOT NULL,
    price_id TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL DEFAULT 1,
    -- Price/cost snapshotted at the moment this line was added — so a
    -- later Price List edit can't retroactively change what an
    -- already-billed stay owes, or this month's revenue/COGS report for
    -- an already-logged procedure. unit_cost stays nullable: not every
    -- price_list row necessarily has a cost_price set (Services
    -- typically don't carry a COGS basis).
    unit_price DOUBLE PRECISION,
    unit_cost DOUBLE PRECISION,
    logged_by TEXT,
    timestamp TEXT NOT NULL,
    FOREIGN KEY (case_id) REFERENCES inpatient_cases(id),
    FOREIGN KEY (price_id) REFERENCES price_list(id)
);
CREATE INDEX IF NOT EXISTS idx_inpbilling_case ON inpatient_billing(case_id);

