-- Vetzone IQ database schema — v3 (PostgreSQL)
-- Ported from the original SQLite schema.sql. Table/column names, types,
-- and constraints are unchanged except: AUTOINCREMENT -> IDENTITY, and
-- REAL -> DOUBLE PRECISION (same practical behavior, more standard on PG).

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

-- Atomic ID-allocation counters (P001, V002, IC003, ...). Replaces the old
-- MAX(id)+1-in-Python approach, which was not safe under concurrent use.
CREATE TABLE IF NOT EXISTS id_counters (
    prefix TEXT PRIMARY KEY,
    next_val INTEGER NOT NULL DEFAULT 1
);

-- History of nightly/manual database backups, shown in Settings.
CREATE TABLE IF NOT EXISTS backup_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TEXT NOT NULL,
    finished_at TEXT,
    status TEXT NOT NULL CHECK (status IN ('running','success','failed')),
    filepath TEXT,
    filesize_bytes BIGINT,
    error TEXT,
    triggered_by TEXT  -- 'manual' / 'nightly' / 'shutdown' — NULL for older rows predating this column
);
CREATE INDEX IF NOT EXISTS idx_backup_log_started ON backup_log(started_at);

CREATE TABLE IF NOT EXISTS restore_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TEXT NOT NULL,
    finished_at TEXT,
    status TEXT NOT NULL CHECK (status IN ('success','failed')),
    source_file TEXT,
    error TEXT,
    triggered_by TEXT
);
CREATE INDEX IF NOT EXISTS idx_restore_log_started ON restore_log(started_at);


-- ============================================================ AUTH / USERS / ROLES
-- Roles are no longer a fixed 3-value list. Admin is the one system role
-- (is_system=1) — locked, always has every permission, can't be renamed/
-- deleted. Every other role (including the seeded Vet/Reception) is an
-- ordinary custom role: rename it, delete it, edit its permission
-- checklist and discount cap freely.
CREATE TABLE IF NOT EXISTS roles (
    id TEXT PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    description TEXT,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    discount_cap INTEGER NOT NULL DEFAULT 0 CHECK (discount_cap BETWEEN 0 AND 100),
    -- Whether staff with this role can be assigned as the attending vet
    -- (Appointments grid, New Visit, Grooming, Inpatient). Deliberately a
    -- role attribute rather than a hardcoded role NAME check, so renaming
    -- or restructuring the "Vet" role can't silently empty every vet
    -- picker in the app the way it used to.
    is_vet_role BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TEXT NOT NULL
);

-- Static seed list of every permission key the app understands — not
-- admin-editable itself, just the fixed vocabulary of what *can* be gated.
-- Kept in sync with auth.PERMISSIONS on every launch.
CREATE TABLE IF NOT EXISTS permissions (
    id TEXT PRIMARY KEY,
    label TEXT NOT NULL,
    category TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id TEXT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id TEXT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role_id TEXT NOT NULL REFERENCES roles(id),
    custom_discount_cap INTEGER CHECK (custom_discount_cap BETWEEN 0 AND 100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role_id);

CREATE TABLE IF NOT EXISTS login_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    username TEXT,
    success INTEGER NOT NULL,
    timestamp TEXT NOT NULL,
    ip TEXT,
    user_agent TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    username TEXT,
    timestamp TEXT NOT NULL,
    action TEXT NOT NULL,          -- 'create' / 'update' / 'delete'
    table_name TEXT NOT NULL,
    record_id TEXT NOT NULL,
    field TEXT,
    old_value TEXT,
    new_value TEXT
);
CREATE INDEX IF NOT EXISTS idx_audit_ts ON audit_log(timestamp);

